  let current = 'zh-CN';

  const detect = () => {
    const saved = localStorage.getItem(STORE_KEY);
    if (saved && SUPPORTED.includes(saved)) return saved;
    const q = new URLSearchParams(location.search).get('lang');
    if (q && SUPPORTED.includes(q)) return q;
    const prefs = [].concat(navigator.languages || [], navigator.language || []).filter(Boolean);
    for (const p of prefs) {
      const lc = String(p).toLowerCase();
      if (lc.startsWith('zh')) return /tw|hk|mo|hant/.test(lc) ? 'zh-TW' : 'zh-CN';
      if (lc.startsWith('en')) return 'en';
      if (lc.startsWith('fr')) return 'fr';
      if (lc.startsWith('ja')) return 'ja';
      if (lc.startsWith('ko')) return 'ko';
    }
    return 'zh-CN';
  };

  const t = (key, vars) => {
    // 用 key 是否存在判断，而不是真值——允许词条为空字符串（如日韩语标题的连接词）
    const pick = (dict) => (dict && Object.prototype.hasOwnProperty.call(dict, key) ? dict[key] : undefined);
    let s = pick(DICT[current]);
    if (s === undefined) s = pick(DICT['zh-CN']);
    if (s === undefined) s = pick(DICT.en);
    if (s === undefined) s = key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(v);
    return s;
  };

  const applyI18n = (root = document) => {
    root.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });
    root.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });
    root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });
  };

  const setLocale = (loc) => {
    if (!SUPPORTED.includes(loc)) loc = 'zh-CN';
    current = loc;
    try {
      localStorage.setItem(STORE_KEY, loc);
    } catch {}
    document.documentElement.lang = loc;
    applyI18n();
    window.dispatchEvent(new CustomEvent('localechange', { detail: loc }));
  };

  /** 初始化语言选择器（两个页面共用） */
  const mountSwitcher = () => {
    const sel = document.getElementById('langSelect');
    if (!sel) return;
    sel.innerHTML = SUPPORTED.map((l) => `<option value="${l}">${NAMES[l]}</option>`).join('');
    sel.value = current;
    sel.setAttribute('aria-label', t('lang.label'));
    sel.addEventListener('change', () => setLocale(sel.value));
  };

  current = detect();
  document.documentElement.lang = current;
  window.addEventListener('DOMContentLoaded', () => {
    applyI18n();
    mountSwitcher();
    window.dispatchEvent(new CustomEvent('localechange', { detail: current }));
  });

  window.I18N = { t, setLocale, getLocale: () => current, applyI18n, mountSwitcher, SUPPORTED, NAMES };
